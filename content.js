/* ============================================================
   Shared hero animation: an automation graph where jobs enter,
   route through steps and clear. DPR capped at 1.5, glow cached
   to a sprite, paused off-screen and when the tab is hidden.
   ============================================================ */
window.ID_HERO=function(host,REDUCED){
  if(!host) return;
  const cv=document.createElement('canvas');
  host.insertBefore(cv,host.firstChild);
  const ctx=cv.getContext('2d');
  let w=0,h=0,small=false;
  const N=[{x:.04,y:.50,l:'intake'},{x:.24,y:.24,l:'qualify'},{x:.24,y:.76,l:'enrich'},
    {x:.46,y:.50,l:'route'},{x:.68,y:.18,l:'schedule'},{x:.68,y:.50,l:'quote'},
    {x:.68,y:.82,l:'follow-up'},{x:.88,y:.32,l:'crm'},{x:.88,y:.68,l:'report'}];
  const ROUTES=[[0,1,3,4,7],[0,2,3,5,7],[0,1,3,6,8],[0,2,3,6,8],[0,1,3,5,7]];
  const E=[];
  ROUTES.forEach(r=>{for(let i=0;i<r.length-1;i++){const k=r[i]+'-'+r[i+1];
    if(!E.some(e=>e.k===k))E.push({k,a:r[i],b:r[i+1]});}});
  let packets=[],pulses=[],acc=0;
  const GLOW=(()=>{const s=document.createElement('canvas');s.width=s.height=24;
    const c=s.getContext('2d'),g=c.createRadialGradient(12,12,0,12,12,12);
    g.addColorStop(0,'rgba(85,99,206,0.30)');g.addColorStop(1,'rgba(85,99,206,0)');
    c.fillStyle=g;c.fillRect(0,0,24,24);return s;})();
  const px=n=>(0.05+N[n].x*0.90)*w, py=n=>(0.10+N[n].y*0.80)*h;
  function size(){const r=host.getBoundingClientRect();
    const dpr=Math.min(devicePixelRatio||1,1.5);
    w=Math.max(1,Math.round(r.width));h=Math.max(1,Math.round(r.height));
    cv.width=Math.round(w*dpr);cv.height=Math.round(h*dpr);
    ctx.setTransform(dpr,0,0,dpr,0,0);small=w<900;}
  function spawn(){if(packets.length<26)
    packets.push({r:ROUTES[(Math.random()*ROUTES.length)|0],i:0,t:Math.random()*.2,sp:.3+Math.random()*.3});}
  size();for(let i=0;i<10;i++)spawn();
  new ResizeObserver(size).observe(host);
  function step(dt){acc+=dt;if(acc>.5){acc=0;spawn();}
    for(let k=packets.length-1;k>=0;k--){const p=packets[k];p.t+=dt*p.sp;
      while(p.t>=1){p.t-=1;p.i++;
        if(p.i>=p.r.length-1){pulses.push({n:p.r[p.r.length-1],t:0});packets.splice(k,1);break;}
        pulses.push({n:p.r[p.i],t:0});}}
    for(let k=pulses.length-1;k>=0;k--){pulses[k].t+=dt*1.8;if(pulses[k].t>1)pulses.splice(k,1);}}
  function draw(){ctx.clearRect(0,0,w,h);if(small)return;
    ctx.lineWidth=1;ctx.strokeStyle='rgba(85,99,206,0.20)';
    E.forEach(e=>{const x1=px(e.a),y1=py(e.a),x2=px(e.b),y2=py(e.b),mx=(x1+x2)/2;
      ctx.beginPath();ctx.moveTo(x1,y1);ctx.bezierCurveTo(mx,y1,mx,y2,x2,y2);ctx.stroke();});
    N.forEach((n,i)=>{const x=px(i),y=py(i);
      ctx.fillStyle='rgba(255,255,255,.98)';ctx.strokeStyle='rgba(85,99,206,.40)';
      ctx.beginPath();ctx.arc(x,y,5.5,0,Math.PI*2);ctx.fill();ctx.stroke();
      ctx.font='500 10px "JetBrains Mono", monospace';ctx.fillStyle='rgba(63,77,180,.38)';
      ctx.textAlign='center';ctx.fillText(n.l,x,y-13);});
    pulses.forEach(p=>{const x=px(p.n),y=py(p.n),r=5.5+p.t*15;
      ctx.strokeStyle='rgba(18,118,76,'+((1-p.t)*.42).toFixed(3)+')';
      ctx.lineWidth=1.5;ctx.beginPath();ctx.arc(x,y,r,0,Math.PI*2);ctx.stroke();});
    packets.forEach(p=>{const a=p.r[p.i],b=p.r[p.i+1];if(b===undefined)return;
      const x1=px(a),y1=py(a),x2=px(b),y2=py(b),mx=(x1+x2)/2,t=p.t,u=1-t;
      const x=u*u*u*x1+3*u*u*t*mx+3*u*t*t*mx+t*t*t*x2;
      const y=u*u*u*y1+3*u*u*t*y1+3*u*t*t*y2+t*t*t*y2;
      ctx.drawImage(GLOW,x-12,y-12);
      ctx.fillStyle='rgba(196,56,15,.95)';ctx.beginPath();ctx.arc(x,y,2,0,Math.PI*2);ctx.fill();});}
  if(REDUCED){for(let k=0;k<60;k++)step(.05);draw();return;}
  let raf=0,last=performance.now(),vis=true;
  function frame(now){const dt=Math.min((now-last)/1000,.05);last=now;step(dt);draw();raf=requestAnimationFrame(frame);}
  function run(on){cancelAnimationFrame(raf);if(on&&!document.hidden){last=performance.now();raf=requestAnimationFrame(frame);}}
  new IntersectionObserver(es=>{vis=es[0].isIntersecting;run(vis);},{threshold:0}).observe(host);
  document.addEventListener('visibilitychange',()=>run(vis&&!document.hidden));
  raf=requestAnimationFrame(frame);
};
